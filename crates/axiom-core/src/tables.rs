//! Calibrated radial routes: piecewise-linear tables over r ∈ [0, 1].
//!
//! A *route* is what you meet walking out along a spoke of the parameter
//! disk. At r = 0 every anchor is a strongly damped system with a single
//! stable fixed point (so the centre is calm whatever the blend); as r grows
//! its bifurcation parameters `p(r)` carry it through a Hopf bifurcation to a
//! limit cycle (on some routes a torus), then a strange attractor, and on the
//! rim the chaotic values (Thomas' damping falls far enough there to make a
//! labyrinth, and then far enough more, to b = 0.0025, that the labyrinth shows
//! no lattice weave: see `examples/calibrate/routes.rs`). The rest of a row
//! keeps the attractor usable while `p` moves: the centre `c` and length `L`
//! place and scale it inside the unit ball, and the time scale `τ` and
//! characteristic angular frequency `ω` keep particles at a lively pace and
//! give the synth its pitch reference. Rows were tuned with
//! `examples/calibrate`.
//!
//! Row layout: `[r, p0..p7, cx, cy, cz, L, tau, omega]`.
//! The data between the markers is generated by
//! `cargo run --release --example calibrate -- write` from the route
//! definitions in `examples/calibrate/routes.rs` — do not edit it by hand.
//! `ANCHORS` lists the kinds that have a route (Halvorsen has none), and
//! `KAPPA0`/`KAPPA_R` shape the centre damping (see `law::kappa`).

